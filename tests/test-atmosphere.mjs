import assert from 'node:assert/strict';
let draws=0;
const g={createRadialGradient:()=>({addColorStop(){}}),fillRect(){},save(){},restore(){},drawImage(...args){draws++;assert.ok(args.slice(1).every(Number.isFinite));}};
globalThis.document={createElement:()=>({getContext:()=>g})};
const {Atmosphere}=await import('../dist/atmosphere.js');
const fx=new Atmosphere(),head={x:300,y:420,rx:140,ry:220};
assert.equal(fx.textures.length,3);
for(let i=0;i<180;i++)fx.update(1/60,{head,mode:'rain'});
assert.ok(fx.cool>.99);assert.equal(fx.warm,0);
fx.backdrop(g,600,1066,head,3000,false);
for(let i=0;i<180;i++)fx.update(1/60,{head,mode:'bloom'});
assert.ok(fx.warm>.99);assert.ok(fx.cool<.001);
for(let i=0;i<100;i++)fx.burst(300,200,true,false);
assert.equal(fx.pulses.length,6,'burst-light storage must remain bounded');
fx.foreground(g,600,1066,head,{active:true,x:400,y:600},1,[{life:.4,x:140,y:420}],false);
for(let i=0;i<240;i++)fx.update(1/60,{head,mode:'still'});
assert.ok(fx.cool+fx.warm<.001);assert.ok(fx.pulses.every(p=>p.life===0));
fx.burst(200,200,true,true);assert.ok(fx.pulses.every(p=>p.life===0),'reduced motion removes burst pulses');
fx.update(.05,{head,mode:'rain'});fx.update(.05,{head:null,mode:'rain'});assert.equal(fx.cool,0);
fx.update(.05,{head,mode:'bloom'});fx.update(.05,{head,mode:'bloom',suspended:true});assert.equal(fx.warm,0);
assert.ok(draws>0);
console.log(JSON.stringify({passed:true,textures:3,lightPool:6,checks:['rain to warm transition','bounded light impulses','natural fade','reduced motion','face loss','pause reset','finite draw coordinates']}));
